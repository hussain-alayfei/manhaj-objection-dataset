"""Regenerate supabase/migrations/<INITIAL>_initial.sql from the SQLAlchemy tables.

The initial migration is append-only history once applied anywhere; schema changes after that
belong in new files created with `npx supabase migration new <name>`.
"""
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from sqlalchemy.schema import CreateTable
from sqlalchemy.dialects import postgresql
from src.db import metadata

INITIAL = '20261004000000'
# No BEGIN/COMMIT: `supabase db push` and `psql -1` wrap each migration in one transaction.
# pgvector lives in the `extensions` schema (Supabase convention); vector types are schema-qualified
# here, while runtime SQL relies on a search_path that includes `extensions`.
sql = f'-- {INITIAL}: initial Manhaj schema (generated by scripts/generate_migration.py).\n'
sql += 'CREATE SCHEMA IF NOT EXISTS extensions;\nCREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;\n\n'
for table in metadata.sorted_tables:
    sql += str(CreateTable(table).compile(dialect=postgresql.dialect())).strip() + ';\n\n'
sql += '''CREATE TABLE semantic_vectors (
    id TEXT PRIMARY KEY REFERENCES embeddings(id) ON DELETE CASCADE,
    record_id TEXT NOT NULL,
    record_version INTEGER NOT NULL,
    model TEXT NOT NULL,
    embedding extensions.vector(768) NOT NULL
);
CREATE INDEX semantic_vectors_hnsw ON semantic_vectors USING hnsw (embedding extensions.vector_cosine_ops);
CREATE INDEX source_chunks_source_page ON source_chunks(source_id, page_number);
CREATE INDEX reviews_record ON reviews(record_id);
CREATE INDEX record_versions_lookup ON record_versions(record_id, version);
CREATE INDEX embeddings_current ON embeddings(record_id, record_version, model);
CREATE FUNCTION manhaj_immutable_audit() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN RAISE EXCEPTION 'Audit history is append-only'; END; $$;
CREATE TRIGGER reviews_immutable BEFORE UPDATE OR DELETE ON reviews FOR EACH ROW EXECUTE FUNCTION manhaj_immutable_audit();
CREATE TRIGGER versions_immutable BEFORE UPDATE OR DELETE ON record_versions FOR EACH ROW EXECUTE FUNCTION manhaj_immutable_audit();
'''
for table in ('objections', 'methodology_rules', 'objection_families'):
    sql += f'''ALTER TABLE {table} ADD CONSTRAINT {table}_status CHECK (status IN ('draft','needs_review','approved','rejected'));
ALTER TABLE {table} ADD CONSTRAINT {table}_phase CHECK (phase IN (1,2));
ALTER TABLE {table} ADD CONSTRAINT {table}_version CHECK (version >= 1);
ALTER TABLE {table} ADD CONSTRAINT {table}_payload_status CHECK (payload->>'review_status' = status);
CREATE INDEX {table}_status_phase ON {table}(status,phase);
CREATE INDEX {table}_keywords ON {table} USING gin(to_tsvector('simple', coalesce(payload->>'normalized_objection_ar','') || ' ' || coalesce(payload->>'methodology_rule_ar','')));
'''
out = Path('supabase/migrations') / f'{INITIAL}_initial.sql'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(sql, encoding='utf-8', newline='\n')
print(out)
